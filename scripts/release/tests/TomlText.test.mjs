import { describe, expect, it } from 'vitest';
import { TomlText } from '../lib/TomlText.mjs';

const MANIFEST = `[workspace]
members = ["crates/*", "apps/desktop/src-tauri"]

# Quelle der Version
[workspace.package]
version = "0.1.0" # hier steht sie
edition = "2021"

[package]
name = "fix-core"
version.workspace = true
`;

const LOCK = `# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "fix-core"
version = "0.1.0"

[[package]]
name = "serde"
version = "1.0.210"
checksum = "abc"
`;

describe('TomlText', () => {
  it('liest einen Wert aus dem richtigen Abschnitt', () => {
    const toml = new TomlText(MANIFEST);
    expect(toml.string('workspace.package', 'version')).toBe('0.1.0');
    expect(toml.string('workspace.package', 'edition')).toBe('2021');
    expect(toml.string('package', 'name')).toBe('fix-core');
  });

  it('unterscheidet gleiche Schlüssel in verschiedenen Abschnitten', () => {
    const toml = new TomlText(LOCK);
    // Oberhalb jedes Abschnitts steht die Version des Lock-Formats, nicht die eines Pakets
    expect(toml.raw('', 'version')).toBe('4');
    expect(toml.string('', 'version')).toBeUndefined();
  });

  it('kennt `version.workspace` als eigenen Schlüssel', () => {
    const toml = new TomlText(MANIFEST);
    expect(toml.raw('package', 'version.workspace')).toBe('true');
    expect(toml.string('package', 'version')).toBeUndefined();
  });

  it('liefert undefined für Schlüssel und Abschnitte, die es nicht gibt', () => {
    const toml = new TomlText(MANIFEST);
    expect(toml.string('workspace.package', 'gibtsnicht')).toBeUndefined();
    expect(toml.string('gibtsnicht', 'version')).toBeUndefined();
    expect(toml.hasSection('workspace.package')).toBe(true);
    expect(toml.hasSection('gibtsnicht')).toBe(false);
  });

  it('setzt nur die Zeichenkette und lässt Kommentar und Rest stehen', () => {
    const toml = new TomlText(MANIFEST);
    toml.setString('workspace.package', 'version', '0.2.0');
    expect(toml.text).toBe(MANIFEST.replace('"0.1.0"', '"0.2.0"'));
    expect(toml.text).toContain('version = "0.2.0" # hier steht sie');
  });

  it('wirft beim Setzen eines Schlüssels, den es nicht gibt', () => {
    expect(() => new TomlText(MANIFEST).setString('package', 'version', '0.2.0')).toThrow(/gibt es im Abschnitt/);
  });

  it('liest eine Liste aus Zeichenketten', () => {
    expect(new TomlText(MANIFEST).array('workspace', 'members')).toEqual(['crates/*', 'apps/desktop/src-tauri']);
    expect(new TomlText(MANIFEST).array('workspace', 'gibtsnicht')).toEqual([]);
  });

  it('liest eine Liste über mehrere Zeilen', () => {
    const toml = new TomlText('[workspace]\nmembers = [\n  "a",\n  "b",\n]\n');
    expect(toml.array('workspace', 'members')).toEqual(['a', 'b']);
  });

  it('findet die Abschnitte einer Tabellen-Liste samt Namen', () => {
    expect(new TomlText(LOCK).tables('package').map((table) => table.name)).toEqual(['fix-core', 'serde']);
  });

  it('setzt die Version im richtigen Eintrag der Tabellen-Liste', () => {
    const toml = new TomlText(LOCK);
    const own = toml.tables('package').find((table) => table.name === 'fix-core');
    toml.setString('package', 'version', '0.2.0', own);
    expect(toml.text).toBe(LOCK.replace('"0.1.0"', '"0.2.0"'));
    // Fremdes Paket und die Version des Lock-Formats bleiben
    expect(toml.text).toContain('version = "1.0.210"');
    expect(toml.text).toContain('\nversion = 4\n');
  });

  it('behält Windows-Zeilenenden', () => {
    const toml = new TomlText(MANIFEST.replaceAll('\n', '\r\n'));
    expect(toml.string('workspace.package', 'version')).toBe('0.1.0');
    toml.setString('workspace.package', 'version', '0.2.0');
    expect(toml.text).toBe(MANIFEST.replace('"0.1.0"', '"0.2.0"').replaceAll('\n', '\r\n'));
  });
});
